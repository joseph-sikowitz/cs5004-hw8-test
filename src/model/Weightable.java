package model;

/**
 * The Weightable interface defines types that have a weight associated with them.
 *
 * @author Joe Sikowitz
 * @author Vasilios Nicholas
 */
public interface Weightable {

  /**
   * The getWeight() method gets a Weightable's weight.
   *
   * @return double of Weightable's weight.
   */
  double getWeight();
}
